// 解析成语，提取首字和尾字
function parseIdiom(word: string): IdiomInfo {
  return {
    word,
    first: word[0],
    last: word[word.length - 1],
  };
}

// 全部成语（已解析）
export const ALL_IDIOMS: IdiomInfo[] = IDIOM_RAW.map(parseIdiom);

// 按首字索引：{ '一': [idiom1, idiom2, ...], ... }
const byFirstChar: Record<string, IdiomInfo[]> = {};
for (const idiom of ALL_IDIOMS) {
  const key = idiom.first;
  if (!byFirstChar[key]) byFirstChar[key] = [];
  byFirstChar[key].push(idiom);
}

/**
 * 根据首字查找所有可接的成语
 */
export function findIdiomsByFirstChar(char: string): IdiomInfo[] {
  return byFirstChar[char] || [];
}

/**
 * 根据首字随机获取一个成语
 */
export function getRandomIdiomByFirstChar(char: string, exclude: Set<string> = new Set()): IdiomInfo | null {
  const candidates = (byFirstChar[char] || []).filter(i => !exclude.has(i.word));
  if (candidates.length === 0) return null;
  return candidates[Math.floor(Math.random() * candidates.length)];
}

/**
 * 随机获取一个成语（游戏开始时用）
 */
export function getRandomIdiom(): IdiomInfo {
  return ALL_IDIOMS[Math.floor(Math.random() * ALL_IDIOMS.length)];
}

/**
 * 验证是否为合法成语
 */
export function isValidIdiom(word: string): boolean {
  return ALL_IDIOMS.some(i => i.word === word);
}

/**
 * 验证接龙是否合法：首字匹配 + 是成语 + 未用过
 */
export function validateIdiomChain(
  word: string,
  requiredFirstChar: string,
  usedSet: Set<string>,
): { valid: boolean; error?: string } {
  if (!word || word.length !== 4) {
    return { valid: false, error: '请输入四字成语' };
  }
  if (word[0] !== requiredFirstChar) {
    return { valid: false, error: `需要以"${requiredFirstChar}"开头` };
  }
  if (!isValidIdiom(word)) {
    return { valid: false, error: `"${word}"不是有效成语` };
  }
  if (usedSet.has(word)) {
    return { valid: false, error: `"${word}"已经用过了` };
  }
  return { valid: true };
}
